// Generates src/lib/emoji-data.ts from Unicode's own keyboard test list, so the picker
// carries the same emoji an Instagram keyboard offers, grouped in the same order.
import fs from 'node:fs';

const source = fs.readFileSync('/tmp/emoji-test.txt', 'utf8');
const groups = [];
let group = null;

for (const line of source.split('\n')) {
  const named = line.match(/^# group: (.+)$/);
  if (named) {
    group = { name: named[1], items: [] };
    groups.push(group);
    continue;
  }
  if (!group || !line.includes('; fully-qualified')) continue;
  const [left, comment] = line.split('#');
  const points = left.split(';')[0].trim().split(/\s+/).filter(Boolean);
  if (!points.length) continue;
  const char = String.fromCodePoint(...points.map(p => Number.parseInt(p, 16)));
  // Comments look like "😀 E1.0 grinning face": drop the glyph and the version marker.
  const name = comment.trim().split(/\s+/).slice(1).join(' ').replace(/^E\d+\.\d+\s+/, '').split(/[;(]/)[0].trim().toLowerCase();
  group.items.push([char, name]);
}

const ICONS = {
  'Smileys & Emotion': '\u{1F600}',
  'People & Body': '\u{1F44B}',
  'Animals & Nature': '\u{1F431}',
  'Food & Drink': '\u{1F353}',
  'Travel & Places': '\u{2708}\uFE0F',
  'Activities': '\u{26BD}',
  'Objects': '\u{1F4F1}',
  'Symbols': '\u{2764}\uFE0F',
  'Flags': '\u{1F3F4}',
};

const keep = groups.filter(entry => entry.items.length);
const out = [];
out.push('// Generated by dev/build-emoji.mjs from Unicode emoji-test.txt (UTS #51, v15.1).');
out.push('// Do not edit by hand: it is the full keyboard set, in Unicode order.');
out.push('');
out.push('export type EmojiItem = readonly [emoji: string, name: string];');
out.push('export type EmojiCategory = { id: string; label: string; icon: string; items: readonly EmojiItem[] };');
out.push('');
out.push('export const EMOJI_CATEGORIES: readonly EmojiCategory[] = [');
for (const entry of keep) {
  const id = entry.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const rows = entry.items.map(([e, n]) => `  ['${e}', '${n}'],`).join('\n');
  out.push(`  { id: ${JSON.stringify(id)}, label: ${JSON.stringify(entry.name)}, icon: ${JSON.stringify(ICONS[entry.name] ?? '\u2B50')}, items: [`);
  out.push(rows);
  out.push('  ] },');
}
out.push('];');
out.push('');
out.push('/** The row Instagram opens with: the most used faces and hearts, hand-picked. */');
out.push('export const POPULAR: readonly string[] = [');
const wanted = ['grinning face', 'beaming face with smiling eyes', 'face with tears of joy', 'rolling on the floor laughing', 'smiling face with hearts', 'heart eyes', 'kissing face with closed eyes', 'face blowing a kiss', 'woozy face', 'zany face', 'thinking face', 'folded hands', 'clapping hands', 'thumbs up', 'red heart', 'orange heart', 'yellow heart', 'green heart', 'blue heart', 'purple heart', 'sparkling heart', 'heart with arrow', 'fire', 'sparkles', 'star', 'party popper', 'smiling face with halo', 'lying face', 'shushing face', 'face savoring food', 'sun with face', 'cactus', 'rose', 'bouquet', 'champagne glass', 'tropical drink', 'hamburger', 'pizza', 'ice cream', 'doughnut', 'bacon', 'cat face with tears of joy', 'puppy', 'fox', 'panda', 'owl', 'lion', 'whale', 'dolphin', 'butterfly', 'cherry blossom', 'sunflower', 'moon', 'sun', 'rainbow', 'house', 'airplane', 'rocket', 'anchor', 'camera', 'video game', 'jigsaw', 'crown', 'ring', 'gift', 'balloon', 'confetti ball', 'teddy bear', 'pile of poo'];
const byName = new Map();
for (const entry of keep) for (const [e, n] of entry.items) if (!byName.has(n)) byName.set(n, e);
const picked = wanted.map(n => byName.get(n)).filter(Boolean);
out.push(picked.map(e => `  '${e}',`).join('\n'));
out.push('];');
out.push('');
fs.writeFileSync('src/lib/emoji-data.ts', out.join('\n'));
console.log('categories:', keep.length, 'emoji:', keep.reduce((sum, g) => sum + g.items.length, 0), 'popular:', picked.length);
