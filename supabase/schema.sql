-- Our Little Cinema — Supabase schema
-- Run this in the Supabase dashboard: SQL Editor → New query → Run.
--
-- The tables live in `public` because that is the schema PostgREST exposes to the edge
-- function. Row Level Security is switched on with no policies: an anonymous visitor — or any
-- leaked browser key — can read and write nothing at all. Only the function's server-side key
-- (the service role key, which never leaves Supabase and never appears in the site's files)
-- bypasses those rules, and that key is what the application routes use.
--
-- Nothing here stores a password. A room's secret is generated by the function and only ever
-- used to sign member tokens.

create table if not exists public.cine_rooms (
  code text primary key,
  secret text not null,
  host_peer text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.cine_peers (
  room text not null,
  peer text not null,
  name text not null,
  color text not null,
  last_seen timestamptz not null default now(),
  typing bigint not null default 0,
  last_read bigint not null default 0,
  call_state text not null default 'idle',
  primary key (room, peer)
);
create index if not exists cine_peers_room_idx on public.cine_peers (room);

create table if not exists public.cine_messages (
  id text primary key,
  room text not null,
  peer text not null,
  name text not null,
  color text not null,
  kind text not null,
  body text not null,
  media text,
  reactions jsonb,
  reply_to text,
  created bigint not null
);
create index if not exists cine_messages_room_created_idx on public.cine_messages (room, created);

create table if not exists public.cine_player (
  room text primary key,
  video text not null default '',
  title text not null default '',
  position integer not null default 0,
  playing integer not null default 0,
  rate integer not null default 1000,
  queue jsonb,
  updated_by text not null default '',
  updated bigint not null default 0
);

create table if not exists public.cine_signals (
  id text primary key,
  room text not null,
  from_peer text not null,
  to_peer text not null,
  kind text not null,
  payload text not null,
  created bigint not null
);
create index if not exists cine_signals_room_created_idx on public.cine_signals (room, created);

create table if not exists public.cine_media (
  id uuid primary key default gen_random_uuid(),
  room text not null,
  peer text not null,
  object_path text not null unique,
  mime text not null,
  bytes integer not null,
  kind text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now()
);
create index if not exists cine_media_room_status_idx on public.cine_media (room, status);

-- Deny everything to every non-privileged role. The edge function is not one of those roles.
alter table public.cine_rooms enable row level security;
alter table public.cine_peers enable row level security;
alter table public.cine_messages enable row level security;
alter table public.cine_player enable row level security;
alter table public.cine_signals enable row level security;
alter table public.cine_media enable row level security;

