// Keeps the deployed copies of the application in step with their sources.
//
//   node scripts/sync-function.mjs           # refresh both deploy artifacts
//   node scripts/sync-function.mjs --check   # fail if either is stale (the deploy workflow runs this)
//
// Two artifacts, because Supabase offers two ways to ship an edge function:
//   supabase/functions/app/routes.mjs   — the folder the CLI bundles (index.ts + _shared/backend.ts)
//   supabase/paste-this-function.ts     — the same program as one file, for the dashboard's editor
// Neither may be hand-edited: both are generated from functions/routes.mjs and
// supabase/functions/_shared/backend.ts, so the app logic has exactly one source of truth.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const paths = {
  routes: `${root}functions/routes.mjs`,
  backend: `${root}supabase/functions/_shared/backend.ts`,
  entry: `${root}supabase/functions/app/index.ts`,
  copy: `${root}supabase/functions/app/routes.mjs`,
  single: `${root}supabase/paste-this-function.ts`,
};

const sources = {};
for (const [name, path] of Object.entries(paths)) {
  if (name === 'copy' || name === 'single') continue;
  sources[name] = await readFile(path, 'utf8');
}

const copy = sources.routes;

// The dashboard editor takes one file, so the module imports disappear and the three bodies
// are laid down in dependency order: the provider client import, the adapter, the routes,
// then the entry point that wires them together.
const providerImport = (sources.backend.match(/^import .*$/m) ?? [''])[0];
const stripImports = text => text.replace(/^import[\s\S]*?from '.*';\n/gm, '').replace(/^\/\/ deno-lint-ignore-file.*\n/, '');
const stripFileHeader = text => text.replace(/^\/\/[\s\S]*?\n\n/, '');
const single = [
  '// Our Little Cinema — Supabase edge function, as one file for the dashboard editor.',
  '// GENERATED by scripts/sync-function.mjs. Edit functions/routes.mjs or',
  '// supabase/functions/_shared/backend.ts instead, then run `npm run function:sync`.',
  '',
  providerImport,
  '',
  stripFileHeader(stripImports(sources.backend)),
  stripFileHeader(sources.routes),
  stripFileHeader(stripImports(sources.entry)),
].join('\n');

const expected = { [paths.copy]: copy, [paths.single]: single };

if (process.argv.includes('--check')) {
  for (const [path, content] of Object.entries(expected)) {
    let current = null;
    try { current = await readFile(path, 'utf8'); } catch { /* never written */ }
    if (current !== content) {
      console.error(`${path.replace(root, '')} is out of date.`);
      console.error('Run: npm run function:sync');
      process.exit(1);
    }
  }
  console.log('edge function copies are current');
} else {
  await mkdir(paths.copy.replace(/\/[^/]+$/, ''), { recursive: true });
  for (const [path, content] of Object.entries(expected)) await writeFile(path, content, 'utf8');
  console.log('refreshed supabase/functions/app/routes.mjs and supabase/paste-this-function.ts');
}
